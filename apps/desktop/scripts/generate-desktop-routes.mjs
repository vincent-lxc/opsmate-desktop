#!/usr/bin/env node
/**
 * Generate matching Rust + TypeScript desktop API route catalogs from
 * apps/desktop/contracts/desktop-api-routes.json (single source of truth).
 *
 * Normalization (identical in both languages):
 * - relative `/api/` path only (no absolute / protocol-relative URLs)
 * - no backslash, no fragment
 * - query stripped (parsed separately; not part of path match)
 * - no encoded slash / backslash / dot segment (%2f / %5c / %2e, any case)
 * - no encoded percent (%25) — blocks double-encoded separators/dot (%252f/%252e/…)
 * - no encoded ASCII controls in path (%00-%1f, %7f)
 * - no empty path segments; no raw "." / ".." segments
 * - blocked paths checked before prefix families
 * - prefix match is exact or prefix + "/"
 * - query is stripped before percent checks (ordinary query % encoding stays allowed)
 *
 * Usage:
 *   node apps/desktop/scripts/generate-desktop-routes.mjs
 *   node apps/desktop/scripts/generate-desktop-routes.mjs --check
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const desktopRoot = resolve(__dirname, "..");
const repoRoot = resolve(desktopRoot, "../..");
const catalogPath = resolve(desktopRoot, "contracts/desktop-api-routes.json");
const rustOutPath = resolve(desktopRoot, "src-tauri/src/cloud_proxy/routes.rs");
const tsOutPath = resolve(repoRoot, "apps/admin/src/desktop/generated-api-routes.ts");

const ALLOWED_METHODS = new Set(["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"]);

function die(msg) {
  console.error(`generate-desktop-routes: ${msg}`);
  process.exit(1);
}

function loadCatalog() {
  let raw;
  try {
    raw = readFileSync(catalogPath, "utf8");
  } catch (e) {
    die(`cannot read ${catalogPath}: ${e.message}`);
  }
  let catalog;
  try {
    catalog = JSON.parse(raw);
  } catch (e) {
    die(`invalid JSON in ${catalogPath}: ${e.message}`);
  }
  if (catalog.version !== 1) {
    die(`version must be 1, got ${JSON.stringify(catalog.version)}`);
  }
  if (!Array.isArray(catalog.families) || catalog.families.length === 0) {
    die("families must be a non-empty array");
  }
  if (!Array.isArray(catalog.blocked)) {
    die("blocked must be an array");
  }
  for (const f of catalog.families) {
    if (typeof f.prefix !== "string" || !f.prefix.startsWith("/api/")) {
      die(`family prefix must start with /api/: ${JSON.stringify(f.prefix)}`);
    }
    if (f.prefix.includes("\\") || f.prefix.includes("?") || f.prefix.includes("#")) {
      die(`family prefix has illegal characters: ${f.prefix}`);
    }
    if (!Array.isArray(f.methods) || f.methods.length === 0) {
      die(`family ${f.prefix} methods must be non-empty`);
    }
    for (const m of f.methods) {
      if (!ALLOWED_METHODS.has(m)) {
        die(`family ${f.prefix} has invalid method ${m}`);
      }
    }
  }
  for (const b of catalog.blocked) {
    if (typeof b !== "string" || !b.startsWith("/api/")) {
      die(`blocked path must start with /api/: ${JSON.stringify(b)}`);
    }
  }
  return catalog;
}

function rustString(s) {
  return JSON.stringify(s);
}

function generateRust(catalog) {
  // Trailing commas keep output cargo-fmt stable (rustfmt requires them here).
  const families = catalog.families
    .map(
      (f) =>
        `    RouteFamily {\n        prefix: ${rustString(f.prefix)},\n        methods: &[${f.methods
          .map((m) => rustString(m))
          .join(", ")}],\n    }`,
    )
    .join(",\n");
  const blocked = catalog.blocked.map((b) => `    ${rustString(b)}`).join(",\n");

  return `// @generated by apps/desktop/scripts/generate-desktop-routes.mjs
// DO NOT EDIT — regenerate with: node apps/desktop/scripts/generate-desktop-routes.mjs
// Source: apps/desktop/contracts/desktop-api-routes.json (version ${catalog.version})

//! Desktop cloud API route allowlist (generated).
//!
//! Matching rules (keep in sync with TypeScript \`generated-api-routes.ts\`):
//! - relative \`/api/\` path only
//! - no backslash, no fragment
//! - query parsed separately (stripped before match)
//! - no encoded slash/backslash/dot segment
//! - no encoded percent (%25) / controls (%00-%1f, %7f) in path
//! - no empty / \`.\` / \`..\` segments
//! - blocked paths checked before prefix families

#![allow(dead_code)]

/// One allowlisted path-prefix family and its HTTP methods.
#[derive(Debug, Clone, Copy)]
pub struct RouteFamily {
    pub prefix: &'static str,
    pub methods: &'static [&'static str],
}

/// Version of the route catalog contract.
pub const CATALOG_VERSION: u32 = ${catalog.version};

/// Allowlisted route families (prefix + methods).
pub static FAMILIES: &[RouteFamily] = &[
${families},
];

/// Explicitly blocked paths (checked before family prefixes).
pub static BLOCKED: &[&str] = &[
${blocked},
];

/// Return true when \`method\` + \`path_with_query\` is allowlisted for desktop cloud proxy.
pub fn match_request(method: &str, path_with_query: &str) -> bool {
    let Some(path) = normalize_path(path_with_query) else {
        return false;
    };
    // Blocked before prefix families.
    if BLOCKED.contains(&path) {
        return false;
    }
    let method_upper = method.to_ascii_uppercase();
    for family in FAMILIES {
        if path_matches_prefix(path, family.prefix)
            && family
                .methods
                .iter()
                .any(|m| m.eq_ignore_ascii_case(&method_upper))
        {
            return true;
        }
    }
    false
}

fn path_matches_prefix(path: &str, prefix: &str) -> bool {
    path == prefix || path.starts_with(&format!("{prefix}/"))
}

/// Normalize a request path for allowlist matching.
///
/// Returns \`None\` when the input is not a safe relative \`/api/\` path.
fn normalize_path(path_with_query: &str) -> Option<&str> {
    if path_with_query.is_empty() {
        return None;
    }
    // No backslash (Windows path smuggling) and no fragment.
    if path_with_query.contains('\\\\') || path_with_query.contains('#') {
        return None;
    }
    // Absolute or protocol-relative URLs are rejected.
    if path_with_query.contains("://") || path_with_query.starts_with("//") {
        return None;
    }
    if !path_with_query.starts_with('/') {
        return None;
    }

    // Query is parsed separately — strip for path match.
    let path = match path_with_query.split_once('?') {
        Some((p, _)) => p,
        None => path_with_query,
    };

    // Must be under /api/ (not merely /api).
    if !path.starts_with("/api/") {
        return None;
    }

    // Reject forbidden percent-encodings in the path only (query already stripped).
    // Blocks: %2e/%2f/%5c, encoded percent %25 (double-encoding), controls %00-%1f/%7f.
    if path_has_forbidden_percent_encoding(path) {
        return None;
    }

    // Segment checks: no empty, no "." / "..".
    // path always starts with '/' so split yields a leading empty str.
    for segment in path.split('/').skip(1) {
        if segment.is_empty() || segment == "." || segment == ".." {
            return None;
        }
    }

    Some(path)
}

/// True when path contains a percent-encoding that is unsafe for allowlist matching.
fn path_has_forbidden_percent_encoding(path: &str) -> bool {
    let bytes = path.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] != b'%' {
            i += 1;
            continue;
        }
        // Incomplete or non-hex percent sequence is rejected.
        if i + 2 >= bytes.len() {
            return true;
        }
        let h1 = bytes[i + 1];
        let h2 = bytes[i + 2];
        let Some(v) = hex_byte(h1, h2) else {
            return true;
        };
        // Encoded controls, DEL, percent (double-encoding), dot, slash, backslash.
        if v <= 0x1f || v == 0x7f || v == 0x25 || v == 0x2e || v == 0x2f || v == 0x5c {
            return true;
        }
        i += 3;
    }
    false
}

fn hex_byte(h1: u8, h2: u8) -> Option<u8> {
    let n1 = hex_nibble(h1)?;
    let n2 = hex_nibble(h2)?;
    Some((n1 << 4) | n2)
}

fn hex_nibble(b: u8) -> Option<u8> {
    match b {
        b'0'..=b'9' => Some(b - b'0'),
        b'a'..=b'f' => Some(b - b'a' + 10),
        b'A'..=b'F' => Some(b - b'A' + 10),
        _ => None,
    }
}

#[cfg(test)]
mod generated_unit_tests {
    use super::*;

    #[test]
    fn catalog_version_is_one() {
        assert_eq!(CATALOG_VERSION, 1);
    }

    #[test]
    fn blocked_before_any_prefix() {
        // Even if a blocked path looked like a family descendant, blocked wins.
        assert!(!match_request("GET", "/api/auth/login"));
        assert!(!match_request("POST", "/api/auth/refresh"));
    }
}
`;
}

function generateTypeScript(catalog) {
  const families = catalog.families
    .map(
      (f) =>
        `  { prefix: ${JSON.stringify(f.prefix)}, methods: [${f.methods
          .map((m) => JSON.stringify(m))
          .join(", ")}] as const }`,
    )
    .join(",\n");
  const blocked = catalog.blocked.map((b) => `  ${JSON.stringify(b)}`).join(",\n");

  return `// @generated by apps/desktop/scripts/generate-desktop-routes.mjs
// DO NOT EDIT — regenerate with: node apps/desktop/scripts/generate-desktop-routes.mjs
// Source: apps/desktop/contracts/desktop-api-routes.json (version ${catalog.version})

/**
 * Desktop cloud API route allowlist (generated).
 *
 * Matching rules (keep in sync with Rust \`cloud_proxy/routes.rs\`):
 * - relative \`/api/\` path only
 * - no backslash, no fragment
 * - query parsed separately (stripped before match)
 * - no encoded slash/backslash/dot segment
 * - no encoded percent (%25) / controls (%00-%1f, %7f) in path
 * - no empty / \`.\` / \`..\` segments
 * - blocked paths checked before prefix families
 */

export const CATALOG_VERSION = ${catalog.version} as const;

export type RouteFamily = {
  readonly prefix: string;
  readonly methods: readonly string[];
};

export const FAMILIES: readonly RouteFamily[] = [
${families}
];

export const BLOCKED: readonly string[] = [
${blocked}
];

/**
 * Return true when \`method\` + \`pathWithQuery\` is allowlisted for desktop cloud proxy.
 */
export function isDesktopApiRequestAllowed(method: string, pathWithQuery: string): boolean {
  const path = normalizePath(pathWithQuery);
  if (path === null) {
    return false;
  }
  // Blocked before prefix families.
  if (BLOCKED.includes(path)) {
    return false;
  }
  const methodUpper = method.toUpperCase();
  for (const family of FAMILIES) {
    if (pathMatchesPrefix(path, family.prefix) && family.methods.includes(methodUpper)) {
      return true;
    }
  }
  return false;
}

function pathMatchesPrefix(path: string, prefix: string): boolean {
  return path === prefix || path.startsWith(prefix + "/");
}

/**
 * Normalize a request path for allowlist matching.
 * Returns null when the input is not a safe relative \`/api/\` path.
 */
function normalizePath(pathWithQuery: string): string | null {
  if (!pathWithQuery) {
    return null;
  }
  // No backslash (Windows path smuggling) and no fragment.
  if (pathWithQuery.includes("\\\\") || pathWithQuery.includes("#")) {
    return null;
  }
  // Absolute or protocol-relative URLs are rejected.
  if (pathWithQuery.includes("://") || pathWithQuery.startsWith("//")) {
    return null;
  }
  if (!pathWithQuery.startsWith("/")) {
    return null;
  }

  // Query is parsed separately — strip for path match.
  const q = pathWithQuery.indexOf("?");
  const path = q === -1 ? pathWithQuery : pathWithQuery.slice(0, q);

  // Must be under /api/ (not merely /api).
  if (!path.startsWith("/api/")) {
    return null;
  }

  // Reject forbidden percent-encodings in the path only (query already stripped).
  // Blocks: %2e/%2f/%5c, encoded percent %25 (double-encoding), controls %00-%1f/%7f.
  if (pathHasForbiddenPercentEncoding(path)) {
    return null;
  }

  // Segment checks: no empty, no "." / "..".
  // path always starts with '/' so split yields a leading empty str.
  const segments = path.split("/");
  for (let i = 1; i < segments.length; i++) {
    const segment = segments[i];
    if (segment === "" || segment === "." || segment === "..") {
      return null;
    }
  }

  return path;
}

/** True when path contains a percent-encoding that is unsafe for allowlist matching. */
function pathHasForbiddenPercentEncoding(path: string): boolean {
  for (let i = 0; i < path.length; i++) {
    if (path.charCodeAt(i) !== 0x25 /* % */) {
      continue;
    }
    // Incomplete or non-hex percent sequence is rejected.
    if (i + 2 >= path.length) {
      return true;
    }
    const v = hexByte(path.charCodeAt(i + 1), path.charCodeAt(i + 2));
    if (v === null) {
      return true;
    }
    // Encoded controls, DEL, percent (double-encoding), dot, slash, backslash.
    if (v <= 0x1f || v === 0x7f || v === 0x25 || v === 0x2e || v === 0x2f || v === 0x5c) {
      return true;
    }
    i += 2; // loop will +1
  }
  return false;
}

function hexByte(h1: number, h2: number): number | null {
  const n1 = hexNibble(h1);
  const n2 = hexNibble(h2);
  if (n1 === null || n2 === null) {
    return null;
  }
  return (n1 << 4) | n2;
}

function hexNibble(b: number): number | null {
  if (b >= 0x30 && b <= 0x39) return b - 0x30; // 0-9
  if (b >= 0x61 && b <= 0x66) return b - 0x61 + 10; // a-f
  if (b >= 0x41 && b <= 0x46) return b - 0x41 + 10; // A-F
  return null;
}
`;
}

function writeIfChanged(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  let existing = null;
  try {
    existing = readFileSync(path, "utf8");
  } catch {
    // missing
  }
  if (existing === content) {
    return false;
  }
  writeFileSync(path, content, "utf8");
  return true;
}

const checkOnly = process.argv.includes("--check");
const catalog = loadCatalog();
const rust = generateRust(catalog);
const ts = generateTypeScript(catalog);

if (checkOnly) {
  let drift = false;
  for (const [path, content] of [
    [rustOutPath, rust],
    [tsOutPath, ts],
  ]) {
    let existing = "";
    try {
      existing = readFileSync(path, "utf8");
    } catch {
      console.error(`generate-desktop-routes: missing ${path}`);
      drift = true;
      continue;
    }
    if (existing !== content) {
      console.error(`generate-desktop-routes: drift in ${path}`);
      drift = true;
    }
  }
  if (drift) {
    process.exit(1);
  }
  console.log("generate-desktop-routes: check ok (no drift)");
  process.exit(0);
}

const rustChanged = writeIfChanged(rustOutPath, rust);
const tsChanged = writeIfChanged(tsOutPath, ts);
console.log(
  `generate-desktop-routes: wrote ${rustOutPath}${rustChanged ? "" : " (unchanged)"}`,
);
console.log(
  `generate-desktop-routes: wrote ${tsOutPath}${tsChanged ? "" : " (unchanged)"}`,
);
